package com.example.stealthbrowser.stealth

import android.net.Uri
import android.webkit.CookieManager
import org.json.JSONArray
import org.json.JSONObject

data class CookieItem(
  val name: String,
  val value: String,
  val domain: String,
  val path: String = "/",
  val secure: Boolean = false,
  val httpOnly: Boolean = false,
  val expirationDate: Long? = null
)

object CookieHelper {

  fun exportCookiesJson(url: String): String {
    val cookieManager = CookieManager.getInstance()
    val cookieString = cookieManager.getCookie(url) ?: return "[]"
    val uri = try { Uri.parse(url) } catch (_: Exception) { null }
    val host = uri?.host ?: "localhost"

    val jsonArray = JSONArray()
    val pairs = cookieString.split(";")
    for (pair in pairs) {
      val trimmed = pair.trim()
      if (trimmed.isEmpty()) continue
      val eqIdx = trimmed.indexOf("=")
      if (eqIdx > 0) {
        val name = trimmed.substring(0, eqIdx).trim()
        val value = trimmed.substring(eqIdx + 1).trim()
        val obj = JSONObject().apply {
          put("name", name)
          put("value", value)
          put("domain", host)
          put("path", "/")
          put("secure", url.startsWith("https://", ignoreCase = true))
          put("httpOnly", false)
        }
        jsonArray.put(obj)
      }
    }
    return jsonArray.toString(2)
  }

  fun exportCookiesNetscape(url: String): String {
    val cookieManager = CookieManager.getInstance()
    val cookieString = cookieManager.getCookie(url) ?: return "# Netscape HTTP Cookie File\n# No cookies found"
    val uri = try { Uri.parse(url) } catch (_: Exception) { null }
    val host = uri?.host ?: "localhost"
    val domainForNetscape = if (!host.startsWith(".")) ".$host" else host

    val sb = StringBuilder()
    sb.append("# Netscape HTTP Cookie File\n")
    sb.append("# Generated by Shakil Stealth Browser Session Manager\n")

    val pairs = cookieString.split(";")
    for (pair in pairs) {
      val trimmed = pair.trim()
      if (trimmed.isEmpty()) continue
      val eqIdx = trimmed.indexOf("=")
      if (eqIdx > 0) {
        val name = trimmed.substring(0, eqIdx).trim()
        val value = trimmed.substring(eqIdx + 1).trim()
        // Format: domain \t TRUE \t path \t FALSE \t expires \t name \t value
        sb.append("$domainForNetscape\tTRUE\t/\tFALSE\t2147483647\t$name\t$value\n")
      }
    }
    return sb.toString()
  }

  fun importCookies(targetUrl: String, rawData: String): Int {
    val trimmed = rawData.trim()
    if (trimmed.isEmpty()) return 0

    val cookieManager = CookieManager.getInstance()
    cookieManager.setAcceptCookie(true)

    val uri = try { Uri.parse(targetUrl) } catch (_: Exception) { null }
    val host = uri?.host ?: "localhost"
    var count = 0

    try {
      // 1. Try parsing as JSON Array
      if (trimmed.startsWith("[") && trimmed.endsWith("]")) {
        val jsonArray = JSONArray(trimmed)
        for (i in 0 until jsonArray.length()) {
          val obj = jsonArray.getJSONObject(i)
          val name = obj.optString("name")
          val value = obj.optString("value")
          val domain = obj.optString("domain", host).removePrefix(".")
          val path = obj.optString("path", "/")
          if (name.isNotEmpty()) {
            val cookieStr = "$name=$value; domain=$domain; path=$path; SameSite=Lax"
            cookieManager.setCookie(targetUrl, cookieStr)
            count++
          }
        }
        cookieManager.flush()
        return count
      }
    } catch (_: Exception) {}

    // 2. Try parsing as Netscape format (tab-separated lines)
    val lines = trimmed.lines()
    for (line in lines) {
      val lineTrim = line.trim()
      if (lineTrim.startsWith("#") || lineTrim.isEmpty()) continue
      val tokens = lineTrim.split("\t")
      if (tokens.size >= 7) {
        val domain = tokens[0].removePrefix(".")
        val path = tokens[2]
        val name = tokens[5]
        val value = tokens[6]
        val cookieStr = "$name=$value; domain=$domain; path=$path; SameSite=Lax"
        cookieManager.setCookie(targetUrl, cookieStr)
        count++
      } else if (lineTrim.contains("=")) {
        // Fallback: simple Name=Value; Name2=Value2
        val pairs = lineTrim.split(";")
        for (p in pairs) {
          val pTrim = p.trim()
          val eqIdx = pTrim.indexOf("=")
          if (eqIdx > 0) {
            val name = pTrim.substring(0, eqIdx).trim()
            val value = pTrim.substring(eqIdx + 1).trim()
            cookieManager.setCookie(targetUrl, "$name=$value; path=/; SameSite=Lax")
            count++
          }
        }
      }
    }

    cookieManager.flush()
    return count
  }

  fun countCookies(rawData: String): Int {
    val trimmed = rawData.trim()
    if (trimmed.isEmpty()) return 0
    if (trimmed.startsWith("[") && trimmed.endsWith("]")) {
      return try { org.json.JSONArray(trimmed).length() } catch (_: Exception) { 0 }
    }
    return trimmed.lines().count { it.isNotBlank() && !it.startsWith("#") && it.contains("=") }
  }
}

